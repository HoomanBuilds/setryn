#!/usr/bin/env node
// Generates contracts/script/DeployArtifacts.sol: the standalone artifact for every contract DeploySetryn creates,
// and the linked-library closure in dependency order. The deployment links and creates these artifacts itself, so
// the deployed bytecode is exactly the full-build artifact that explorer verification compiles.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(root, "contracts");
const out = join(contracts, "out");
const scriptPath = join(contracts, "script", "DeploySetryn.s.sol");
const target = join(contracts, "script", "DeployArtifacts.sol");
const checkOnly = process.argv.includes("--check");

if (!existsSync(out)) throw new Error("Build the contracts first: forge build");

function artifactFor(source, name) {
  const file = source.split("/").pop();
  const path = join(out, file, `${name}.json`);
  if (!existsSync(path)) throw new Error(`Missing artifact ${file}/${name}.json for ${source}:${name}`);
  const artifact = JSON.parse(readFileSync(path, "utf8"));
  const targets = artifact.metadata?.settings?.compilationTarget ?? {};
  if (targets[source] !== name) throw new Error(`Artifact ${file}/${name}.json was not compiled from ${source}`);
  if (!artifact.bytecode?.object || artifact.bytecode.object === "0x") throw new Error(`${source}:${name} has no bytecode`);
  return artifact;
}

/** Source path of every production contract, keyed by contract name, from the artifact directory. */
function productionSources() {
  const sources = new Map();
  for (const directory of readdirSync(out)) {
    if (!directory.endsWith(".sol")) continue;
    for (const file of readdirSync(join(out, directory))) {
      if (!file.endsWith(".json")) continue;
      const artifact = JSON.parse(readFileSync(join(out, directory, file), "utf8"));
      for (const [source, name] of Object.entries(artifact.metadata?.settings?.compilationTarget ?? {})) {
        if (!source.startsWith("src/")) continue;
        if (sources.has(name) && sources.get(name) !== source) throw new Error(`Contract name ${name} is ambiguous`);
        sources.set(name, source);
      }
    }
  }
  return sources;
}

const script = readFileSync(scriptPath, "utf8");
const created = [...new Set([...script.matchAll(/\b_create\(\s*"([A-Za-z0-9_]+)"/g)].map((match) => match[1]))].sort();
if (created.length === 0) throw new Error("DeploySetryn creates no artifacts through _create");
// Every creation must name its contract with a string literal, or it would silently drop out of the manifest.
const creationCalls = script.match(/\b_create\(/g)?.length ?? 0;
const namedCalls = [...script.matchAll(/\b_create\(\s*"([A-Za-z0-9_]+)"/g)].length;
if (creationCalls !== namedCalls) {
  throw new Error(`DeploySetryn has ${creationCalls} _create calls but only ${namedCalls} name a contract literal.`);
}
const sources = productionSources();

const entries = created.map((name) => {
  const source = sources.get(name);
  if (!source) throw new Error(`No production source for ${name}`);
  return { name, source, artifact: artifactFor(source, name) };
});

// Library closure with dependencies first.
const libraries = new Map();
const visiting = new Set();
function visit(source, name) {
  const key = `${source}:${name}`;
  if (libraries.has(key)) return;
  if (visiting.has(key)) throw new Error(`Library cycle through ${key}`);
  visiting.add(key);
  const artifact = artifactFor(source, name);
  for (const [dependencySource, byName] of Object.entries(artifact.bytecode.linkReferences ?? {})) {
    for (const dependency of Object.keys(byName)) visit(dependencySource, dependency);
  }
  visiting.delete(key);
  libraries.set(key, { name, source });
}
for (const entry of entries) {
  for (const [source, byName] of Object.entries(entry.artifact.bytecode.linkReferences ?? {})) {
    for (const name of Object.keys(byName)) visit(source, name);
  }
}

const artifactId = ({ source, name }) => `${source.split("/").pop()}:${name}`;
const lines = [
  "// SPDX-License-Identifier: UNLICENSED",
  "pragma solidity 0.8.37;",
  "",
  "// Generated by scripts/generate-deploy-artifacts.mjs. Do not edit by hand.",
  "",
  "/// @notice Standalone artifacts the deployment creates and the linked libraries they need, dependencies first.",
  "library DeployArtifacts {",
  "    struct LinkedLibrary {",
  "        string artifact;",
  "        string qualifiedName;",
  "    }",
  "",
  "    function linkedLibraries() internal pure returns (LinkedLibrary[] memory libraries) {",
  `        libraries = new LinkedLibrary[](${libraries.size});`,
  ...[...libraries.values()].map(
    (library, index) =>
      `        libraries[${index}] = LinkedLibrary("${artifactId(library)}", "${library.source}:${library.name}");`,
  ),
  "    }",
  "",
  "    function artifactOf(string memory contractName) internal pure returns (string memory) {",
  "        bytes32 key = keccak256(bytes(contractName));",
  ...entries.map(
    (entry) => `        if (key == keccak256("${entry.name}")) return "${artifactId(entry)}";`,
  ),
  '        revert("DeployArtifacts: unknown contract");',
  "    }",
  "}",
  "",
];
// Emit the file exactly as `forge fmt` would, so the contract formatting check stays clean.
const generated = execFileSync("forge", ["fmt", "--raw", "-"], {
  cwd: contracts,
  input: lines.join("\n"),
  encoding: "utf8",
});

if (checkOnly) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== generated) {
    console.error("contracts/script/DeployArtifacts.sol is stale. Run: node scripts/generate-deploy-artifacts.mjs");
    process.exit(1);
  }
  console.log(`DeployArtifacts.sol is current: ${entries.length} contracts, ${libraries.size} linked libraries.`);
} else {
  writeFileSync(target, generated);
  console.log(`Wrote DeployArtifacts.sol: ${entries.length} contracts, ${libraries.size} linked libraries.`);
}
